# Лабораторная 03. Журнал датчика температуры
#
# Датчик измеряет температуру в градусах Цельсия. Если измерить не удалось,
# вместо числа в журнале стоит слово error.
#
# Ввод:  порог тревоги, количество записей n, затем n строк — температура или error
# Вывод: пять строк — записей, ошибок, превышений, максимум, среднее
#
# Пример: ввод 25 / 5 / 24.5 / 30.1 / error / 19 / 27.3 → вывод 5 / 1 / 2 / 30.1 / 25.2
# Условие целиком: README.md рядом с этим файлом.
#
# Максимум и среднее выводите с одним знаком после точки: f"{value:.1f}"
